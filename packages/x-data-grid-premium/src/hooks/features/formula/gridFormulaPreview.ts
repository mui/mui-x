/**
 * The owner field of a computed column draft that has no field yet.
 */
export const DRAFT_COMPUTED_FIELD = '__computed_draft__';

/**
 * Evaluates a DRAFT formula source against the current grid data without
 * committing anything — the formula bar's on-the-fly result preview. Reads are
 * strictly side-effect free: formula-cell dependencies resolve from the
 * committed lookup (state), raw dependencies through `valueGetter` from row
 * data, computed cells from their typed result (the memo the cells share),
 * positions from the live view position context. Nothing is written to the
 * evaluation cache or its invalidation bookkeeping.
 *
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @param {{ id: GridRowId; field: string }} cell The cell the draft belongs to.
 * @param {string} source The draft text, including the leading `=`.
 * @param {{ a1Notation: boolean }} options Whether the draft is written in the A1 dialect.
 * @returns {GridFormulaResult | null} The would-be result, or `null` for a non-formula draft.
 */
export function previewFormulaResult(
  apiRef: RefObject<GridPrivateApiPremium>,
  cell: { id: GridRowId; field: string },
  source: string,
  options: { a1Notation: boolean },
): GridFormulaResult | null {
  if (isEscapedFormulaSource(source)) {
    return { type: 'value', value: unescapeLiteralSource(source) };
  }
  if (!isFormulaSource(source)) {
    return null;
  }
  const currentCell: FormulaCellRef = { id: cell.id, field: cell.field };
  const parsed = parseDraftFormula(apiRef, currentCell, source, options.a1Notation);
  if ('error' in parsed) {
    return parsed.error;
  }
  // The committed values predate the draft: a cycle it closes, directly or
  // through other formula cells, is only found in the graph.
  const dependencies = bindFormulaDependencies(
    currentCell,
    extractFormulaDependencies(parsed.ast),
    parsed.positionContext,
  );
  if (isDraftCellCyclic(apiRef, { cell: currentCell, dependencies }, currentCell)) {
    return CYCLE_RESULT;
  }
  return evaluateDraftFormula(apiRef, currentCell, parsed.ast, parsed.positionContext);
}

type GridFormulaDraftParse =
  { ast: FormulaAstNode; positionContext: FormulaPositionContext } | { error: GridFormulaResult };

function parseDraftFormula(
  apiRef: RefObject<GridPrivateApiPremium>,
  cell: FormulaCellRef,
  source: string,
  a1Notation: boolean,
): GridFormulaDraftParse {
  const positionContext = gridFormulaA1PositionContextSelector(apiRef);
  let expression = getFormulaExpression(source);
  if (a1Notation) {
    // The commit-time conversion, without a fill offset. Canonical text carries
    // no bare A1 tokens and passes through unchanged (the same idempotency the
    // paste path relies on).
    expression = toCanonicalFormula(expression, {
      positionContext,
      anchorCell: { id: cell.id, field: cell.field },
    }).source;
  }
  // Deliberately NOT the interning parser: drafts are transient one-off strings
  // and would grow the intern map by one entry per keystroke.
  const parse = parseFormula(expression);
  if (parse.ast === null) {
    return {
      error: {
        type: 'error',
        code: '#ERROR!',
        message: parse.error?.message ?? 'The formula could not be parsed.',
      },
    };
  }
  return { ast: parse.ast, positionContext };
}

interface GridComputedColumnDraft {
  field: string;
  ast: FormulaAstNode;
  type: GridComputedColumnType | undefined;
  /**
   * The cells that read the draft, each after the cells it reads, evaluated with the draft applied.
   */
  readers: ReadonlySet<FormulaCellKey>;
  /**
   * The static result of a stored computed column that reads the draft, once it is applied.
   * @param {string} field The field of the stored computed column.
   * @returns {GridFormulaResult | null} The static result, or `null` when the column evaluates.
   */
  getStaticResult: (field: string) => GridFormulaResult | null;
  onOtherRowEvaluated: (() => void) | undefined;
}

function evaluateDraftFormula(
  apiRef: RefObject<GridPrivateApiPremium>,
  cell: FormulaCellRef,
  ast: FormulaAstNode,
  positionContext: FormulaPositionContext,
  computedDraft: GridComputedColumnDraft | null = null,
): GridFormulaResult {
  const cache = apiRef.current.caches.formula!;
  const lookup = gridFormulaLookupSelector(apiRef);
  const rowsLookup = gridRowsLookupSelector(apiRef);
  const columnsLookup = gridColumnLookupSelector(apiRef);
  // `undefined` marks an evaluation in progress.
  const draftResults = new Map<FormulaCellKey, GridFormulaResult | undefined>();

  const readDraftResult = (key: FormulaCellKey, evaluate: () => GridFormulaResult) => {
    if (!draftResults.has(key)) {
      draftResults.set(key, undefined);
      draftResults.set(key, evaluate());
    }
    return toResolvedValue(draftResults.get(key) ?? CYCLE_RESULT);
  };

  const readsDraft = (draft: GridComputedColumnDraft, id: GridRowId, field: string) => {
    for (const dependency of cache.computedColumns.dependencyClosure.get(field) ?? []) {
      if (dependency === draft.field || draft.readers.has(createFormulaCellKey(id, dependency))) {
        return true;
      }
    }
    return false;
  };

  const getCellValue = (ref: FormulaCellRef): FormulaScalar | FormulaErrorValue | undefined => {
    const row = rowsLookup[ref.id];
    if (computedDraft !== null && row !== undefined) {
      const key = createFormulaCellKey(ref.id, ref.field);
      if (ref.field === computedDraft.field) {
        if (isAutogeneratedRow(row)) {
          return null;
        }
        const { type } = computedDraft;
        computedDraft.onOtherRowEvaluated?.();
        return readDraftResult(key, () => {
          const result = evaluate(computedDraft.ast, ref, EMPTY_POSITION_CONTEXT);
          return type === undefined ? result : coerceComputedResult(result, type);
        });
      }
      const record = cache.records.get(key);
      const recordAst = record?.parse?.ast;
      if (record !== undefined && recordAst != null && computedDraft.readers.has(key)) {
        return readDraftResult(key, () =>
          evaluate(
            recordAst,
            { id: record.id, field: record.field },
            record.usesPositionContext ? positionContext : EMPTY_POSITION_CONTEXT,
          ),
        );
      }
      const computedRecord = cache.computedColumns.records.get(ref.field);
      const computedAst = computedRecord?.ast;
      if (
        computedRecord !== undefined &&
        computedAst != null &&
        !isAutogeneratedRow(row) &&
        readsDraft(computedDraft, ref.id, ref.field)
      ) {
        return readDraftResult(
          key,
          () =>
            computedDraft.getStaticResult(ref.field) ??
            coerceComputedResult(
              evaluate(computedAst, ref, EMPTY_POSITION_CONTEXT),
              computedRecord.definition.type,
            ),
        );
      }
    }
    const committed = lookup[String(ref.id)]?.[ref.field];
    if (committed !== undefined) {
      return toResolvedValue(committed);
    }
    if (row === undefined) {
      return null;
    }
    const colDef = columnsLookup[ref.field];
    if (colDef === undefined) {
      return undefined;
    }
    if (colDef.computed) {
      return resolveComputedCellValue(apiRef, row, ref.field);
    }
    return getRowValueUtil(row, colDef, apiRef) as FormulaScalar;
  };

  function evaluate(
    target: FormulaAstNode,
    currentCell: FormulaCellRef,
    position: FormulaPositionContext,
  ): GridFormulaResult {
    return evaluateFormula(target, {
      currentCell,
      getCellValue,
      hasRow: (id) => rowsLookup[id] !== undefined,
      hasField: (field) => field === computedDraft?.field || columnsLookup[field] !== undefined,
      position,
      functions: cache.registry,
    });
  }

  // Bottom-up, so that a long chain of cells doesn't nest the evaluations.
  const cellKey = createFormulaCellKey(cell.id, cell.field);
  for (const key of computedDraft?.readers ?? []) {
    const { id, field } = parseFormulaCellKey(key);
    const row = rowsLookup[id];
    if (key !== cellKey && row !== undefined) {
      getCellValue({ id: gridRowIdSelector(apiRef, row), field });
    }
  }
  return evaluate(ast, cell, positionContext);
}

/**
 * Evaluates a computed column DRAFT for one row, as the cell would once the draft is applied.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @param {GridRowId} rowId The row to evaluate.
 * @param {string} field The field of the draft, `''` when it has none yet.
 * @param {string} formula The draft formula, including the leading `=`.
 * @param {object} options The options.
 * @param {string} options.ignoreField The field of the stored definition the draft replaces.
 * @param {GridComputedColumnType} options.type The type the draft cells of the other rows are coerced to, none while it follows the preview. The returned result is not coerced.
 * @param {() => void} options.onOtherRowEvaluated Called when the draft is evaluated on another row, for a cell formula that reads it.
 * @returns {GridFormulaResult | null} The would-be result, or `null` without the formula feature.
 */
export function previewComputedColumnResult(
  apiRef: RefObject<GridPrivateApiPremium>,
  rowId: GridRowId,
  field: string,
  formula: string,
  options: {
    ignoreField?: string;
    type?: GridComputedColumnType;
    onOtherRowEvaluated?: () => void;
  } = {},
): GridFormulaResult | null {
  const cache = apiRef.current.caches.formula;
  if (cache === undefined) {
    return null;
  }
  const scope = createComputedColumnValidationScope(
    apiRef,
    cache,
    gridColumnLookupSelector(apiRef),
    false,
    { intern: false },
  );
  // The result of every row when the draft is invalid, as for a stored definition.
  const { staticResult } = getComputedColumnVerdict(
    { field, headerName: field, formula, type: 'string' },
    scope,
    { ignoreField: options.ignoreField },
  );
  if (staticResult !== null) {
    return staticResult;
  }
  const currentCell: FormulaCellRef = {
    id: rowId,
    field: field === '' ? DRAFT_COMPUTED_FIELD : field,
  };
  // Computed column formulas are read as written, without the A1 conversion.
  const parsed = parseDraftFormula(apiRef, currentCell, formula, false);
  if ('error' in parsed) {
    return parsed.error;
  }
  let computedDraft: GridComputedColumnDraft | null = null;
  if (field !== '' && !scope.columnFields.has(field)) {
    const { fieldRefs } = extractFormulaDependencies(parsed.ast);
    const readers = getComputedColumnDraftReaders(apiRef, { field, fieldRefs }, currentCell);
    if (readers === null) {
      return CYCLE_RESULT;
    }
    const draftScope: GridComputedColumnValidationScope = {
      ...scope,
      referenceableFields: new Set(scope.referenceableFields).add(field),
      computedDependencies: new Map(scope.computedDependencies).set(field, fieldRefs),
    };
    const staticResults = new Map<string, GridFormulaResult | null>();
    computedDraft = {
      field,
      ast: parsed.ast,
      type: options.type,
      readers,
      getStaticResult: (computedField) => {
        const record = cache.computedColumns.records.get(computedField);
        if (record !== undefined && !staticResults.has(computedField)) {
          staticResults.set(
            computedField,
            getComputedColumnVerdict(record.definition, draftScope, { ignoreField: computedField })
              .staticResult,
          );
        }
        return staticResults.get(computedField) ?? null;
      },
      onOtherRowEvaluated: options.onOtherRowEvaluated,
    };
  }
  return evaluateDraftFormula(
    apiRef,
    currentCell,
    parsed.ast,
    parsed.positionContext,
    computedDraft,
  );
}
