import type { RefObject } from '@mui/x-internals/types';
import { GRID_ACTIONS_COLUMN_TYPE, GridCellModes } from '@mui/x-data-grid-pro';
import type { GridRowId } from '@mui/x-data-grid-pro';
import type { GridPrivateApiPremium } from '../../../models/gridApiPremium';
import { columnIndexToLetters, serializeFormulaAst } from './engine';
import type { FormulaCellRefNode, FormulaPositionContext } from './engine';
import { toFormulaFieldReference } from './gridFormulaAutocomplete';
import { gridFormulaA1PositionContextSelector } from './gridFormulaPositionContext';
import type { FormulaReferenceTarget } from './gridFormulaReferenceHighlights';
import type { GridFormulaPickEditable } from './gridFormulaInterfaces';

/**
 * What a picking click points at. Shares its shape with the highlight targets,
 * so the picked reference and its rectangle on the grid describe the same thing.
 */
export type FormulaPickTarget = Extract<FormulaReferenceTarget, { kind: 'cell' }>;

export interface PickedReferenceTextOptions {
  /**
   * `true` when the editor shows the A1 dialect.
   * @default false
   */
  a1Notation?: boolean;
}

/**
 * The reference text a click on `target` writes into the formula of
 * `ownerCell`, in the dialect the editor shows — or `null` when the target
 * cannot be referenced that way:
 *
 * - the formula's own cell;
 * - a column without a position (utility, grouping or hidden column);
 * - a row outside the data band (pinned row, autogenerated group or
 *   aggregation row, filtered-out row).
 *
 * A cell in the formula's own row is written as the field name (`price`), in
 * both dialects. Any other cell is written as `B2` in A1 notation and as
 * `REF(COLUMN("price"), ROW(2))` otherwise. The text is relative (no `$`) and
 * reads back to the same cell: A1 text through `toCanonicalFormula`, canonical
 * text through `parseFormula`.
 */
export function buildPickedReferenceText(
  positionContext: FormulaPositionContext,
  ownerCell: { id: GridRowId; field: string },
  target: FormulaPickTarget,
  options: PickedReferenceTextOptions = {},
): string | null {
  const a1Notation = options.a1Notation === true;
  // Row ids compare under string coercion, like the position context and the
  // grid's row lookup.
  const isOwnerRow = String(target.rowId) === String(ownerCell.id);
  if (isOwnerRow && target.field === ownerCell.field) {
    return null;
  }

  const columnPosition = positionContext.getPositionOfField(target.field);
  if (columnPosition === undefined) {
    return null;
  }
  const rowPosition = positionContext.getPositionOfRowId(target.rowId);
  if (
    rowPosition === undefined ||
    rowPosition < positionContext.dataFromIndex ||
    rowPosition > positionContext.dataToIndex
  ) {
    return null;
  }

  if (isOwnerRow) {
    return toFormulaFieldReference(target.field, a1Notation);
  }

  if (a1Notation) {
    return `${columnIndexToLetters(columnPosition)}${rowPosition}`;
  }

  const node: FormulaCellRefNode = {
    type: 'cellRef',
    column: { kind: 'field', field: target.field },
    // The id as the grid holds it (a number stays a number), whatever the
    // caller passed: `ROW(2)` and `ROW("2")` are different texts.
    row: { kind: 'id', id: positionContext.getRowIdAtPosition(rowPosition)! },
    span: { start: 0, end: 0 },
  };
  return serializeFormulaAst(node);
}

/**
 * Grid-aware wrapper of `buildPickedReferenceText`: reads the live position
 * context, and also refuses targets the pure builder cannot know about — an
 * actions column and a cell that is itself being edited.
 */
export function getPickedReferenceText(
  apiRef: RefObject<GridPrivateApiPremium>,
  ownerCell: { id: GridRowId; field: string },
  target: FormulaPickTarget,
  options: PickedReferenceTextOptions = {},
): string | null {
  const text = buildPickedReferenceText(
    gridFormulaA1PositionContextSelector(apiRef),
    ownerCell,
    target,
    options,
  );
  if (text === null) {
    return null;
  }
  if (apiRef.current.getColumn(target.field)?.type === GRID_ACTIONS_COLUMN_TYPE) {
    return null;
  }
  if (apiRef.current.getCellMode(target.rowId, target.field) === GridCellModes.Edit) {
    return null;
  }
  return text;
}

/**
 * Registers a formula editable as a destination of picked references, for as
 * long as its host is mounted.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @param {GridFormulaPickEditable} editable The editable to register.
 * @returns {() => void} The function that removes the registration.
 */
export function registerFormulaPickEditable(
  apiRef: RefObject<GridPrivateApiPremium>,
  editable: GridFormulaPickEditable,
): () => void {
  const { editables } = apiRef.current.caches.formula!.referencePick;
  editables.add(editable);
  return () => {
    editables.delete(editable);
  };
}

/**
 * The registered editable that holds the DOM focus, which is the one a picked
 * reference is written into.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @returns {GridFormulaPickEditable | null} The focused editable, or `null` when none of them has the focus.
 */
export function getActiveFormulaPickEditable(
  apiRef: RefObject<GridPrivateApiPremium>,
): GridFormulaPickEditable | null {
  for (const editable of apiRef.current.caches.formula!.referencePick.editables) {
    const root = editable.getHandle()?.getRoot();
    if (root && root.ownerDocument.activeElement === root) {
      return editable;
    }
  }
  return null;
}
