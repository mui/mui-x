/**
 * What a picking click points at. Shares its shape with the highlight targets,
 * so the picked reference and its rectangle on the grid describe the same thing.
 */
export type FormulaPickTarget = Extract<FormulaReferenceTarget, { kind: 'cell' }>;

export interface PickedReferenceTextOptions {
  /**
   * `true` when the editor shows the A1 dialect.
   * @default false
   */
  a1Notation?: boolean;
}

/**
 * The reference text a click on `target` writes into the formula of
 * `ownerCell`, in the dialect the editor shows — or `null` when the target
 * cannot be referenced that way:
 *
 * - the formula's own cell;
 * - a column without a position (utility, grouping or hidden column);
 * - a row outside the data band (pinned row, autogenerated group or
 *   aggregation row, filtered-out row).
 *
 * A cell in the formula's own row is written as the field name (`price`), in
 * both dialects. Any other cell is written as `B2` in A1 notation and as
 * `REF(COLUMN("price"), ROW(2))` otherwise. The text is relative (no `$`) and
 * reads back to the same cell: A1 text through `toCanonicalFormula`, canonical
 * text through `parseFormula`.
 */
export function buildPickedReferenceText(
  positionContext: FormulaPositionContext,
  ownerCell: { id: GridRowId; field: string },
  target: FormulaPickTarget,
  options: PickedReferenceTextOptions = {},
): string | null {
  const a1Notation = options.a1Notation === true;
  // Row ids compare under string coercion, like the position context and the
  // grid's row lookup.
  const isOwnerRow = String(target.rowId) === String(ownerCell.id);
  if (isOwnerRow && target.field === ownerCell.field) {
    return null;
  }

  const columnPosition = positionContext.getPositionOfField(target.field);
  if (columnPosition === undefined) {
    return null;
  }
  const rowPosition = positionContext.getPositionOfRowId(target.rowId);
  if (
    rowPosition === undefined ||
    rowPosition < positionContext.dataFromIndex ||
    rowPosition > positionContext.dataToIndex
  ) {
    return null;
  }

  if (isOwnerRow) {
    return toFormulaFieldReference(target.field, a1Notation);
  }

  if (a1Notation) {
    return `${columnIndexToLetters(columnPosition)}${rowPosition}`;
  }

  const node: FormulaCellRefNode = {
    type: 'cellRef',
    column: { kind: 'field', field: target.field },
    // The id as the grid holds it (a number stays a number), whatever the
    // caller passed: `ROW(2)` and `ROW("2")` are different texts.
    row: { kind: 'id', id: positionContext.getRowIdAtPosition(rowPosition)! },
    span: { start: 0, end: 0 },
  };
  return serializeFormulaAst(node);
}

/**
 * Grid-aware wrapper of `buildPickedReferenceText`: reads the live position
 * context, and also refuses targets the pure builder cannot know about — an
 * actions column and a cell that is itself being edited.
 */
export function getPickedReferenceText(
  apiRef: RefObject<GridPrivateApiPremium>,
  ownerCell: { id: GridRowId; field: string },
  target: FormulaPickTarget,
  options: PickedReferenceTextOptions = {},
): string | null {
  const text = buildPickedReferenceText(
    gridFormulaA1PositionContextSelector(apiRef),
    ownerCell,
    target,
    options,
  );
  if (text === null) {
    return null;
  }
  if (apiRef.current.getColumn(target.field)?.type === GRID_ACTIONS_COLUMN_TYPE) {
    return null;
  }
  if (apiRef.current.getCellMode(target.rowId, target.field) === GridCellModes.Edit) {
    return null;
  }
  return text;
}

/**
 * Registers a formula editable as a destination of picked references, for as
 * long as its host is mounted.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @param {GridFormulaPickEditable} editable The editable to register.
 * @returns {() => void} The function that removes the registration.
 */
export function registerFormulaPickEditable(
  apiRef: RefObject<GridPrivateApiPremium>,
  editable: GridFormulaPickEditable,
): () => void {
  const { editables } = apiRef.current.caches.formula!.referencePick;
  editables.add(editable);
  return () => {
    editables.delete(editable);
  };
}

/**
 * The registered editable that holds the DOM focus, which is the one a picked
 * reference is written into.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @returns {GridFormulaPickEditable | null} The focused editable, or `null` when none of them has the focus.
 */
export function getActiveFormulaPickEditable(
  apiRef: RefObject<GridPrivateApiPremium>,
): GridFormulaPickEditable | null {
  for (const editable of apiRef.current.caches.formula!.referencePick.editables) {
    const root = editable.getHandle()?.getRoot();
    if (root && root.ownerDocument.activeElement === root) {
      return editable;
    }
  }
  return null;
}

/**
 * `true` when the props turn reference picking on.
 */
export function isFormulaReferencePickingEnabled(
  props: Pick<
    DataGridPremiumProcessedProps,
    'formulaReferencePicking' | 'disableFormulas' | 'dataSource'
  >,
): boolean {
  return !!props.formulaReferencePicking && !props.disableFormulas && !props.dataSource;
}

/**
 * What a click on a cell does to the formula of `editable`, given the text it
 * shows and its selection.
 */
export function getFormulaPickActionForEditable(
  apiRef: RefObject<GridPrivateApiPremium>,
  editable: GridFormulaPickEditable,
  text: string,
  selection: FormulaPickSelection,
): FormulaPickAction {
  const { ownerCell, a1Notation } = editable;
  const { pending } = apiRef.current.caches.formula!.referencePick;
  return getFormulaPickAction(
    text,
    selection,
    pending !== null && pending.id === ownerCell.id && pending.field === ownerCell.field
      ? pending.pick
      : null,
    {
      a1Notation,
      // A bare name is a reference when it is the name a click on that column writes.
      isFieldName: (name) =>
        apiRef.current.getColumn(name) != null &&
        toFormulaFieldReference(name, a1Notation) === name,
    },
  );
}

/**
 * Shows where the picking session stands:
 *
 * - the root class that gives the cells their picking cursor, while a click
 *   on a cell would write a reference;
 * - the pending reference, whose rectangle the overlay draws solid.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @param {boolean} pickable `true` when a click on a cell would write a reference.
 * @param {FormulaReferenceTarget | null} pendingReference The target of the pending reference.
 */
export function applyFormulaPickFeedback(
  apiRef: RefObject<GridPrivateApiPremium>,
  pickable: boolean,
  pendingReference: FormulaReferenceTarget | null,
): void {
  // Always re-applied: a render of the root with new classes drops a class set here.
  apiRef.current.rootElementRef?.current?.classList.toggle(
    gridClasses['root--formulaReferencePicking'],
    pickable,
  );

  const activeEdit = gridFormulaActiveEditSelector(apiRef);
  if (activeEdit === null || (activeEdit.pendingReference ?? null) === pendingReference) {
    return;
  }
  apiRef.current.setState((state) => {
    if (state.formula.activeEdit === null) {
      return state;
    }
    return {
      ...state,
      formula: {
        ...state.formula,
        activeEdit: {
          ...state.formula.activeEdit,
          pendingReference: pendingReference ?? undefined,
        },
      },
    };
  });
}

/**
 * Ends the picking session: the gesture and the pending reference are
 * forgotten, and the feedback is removed. Called when the edit, or the draft of
 * the formula bar, that the session belongs to ends.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 */
export function clearFormulaPickSession(apiRef: RefObject<GridPrivateApiPremium>): void {
  const session = apiRef.current.caches.formula!.referencePick;
  session.gesture = null;
  session.pending = null;
  applyFormulaPickFeedback(apiRef, false, null);
}

/**
 * Recomputes the picking feedback from the focused editable: its text and its
 * caret decide whether a click would write a reference, and whether the
 * reference of the last pick is still pending. Called after every change of
 * the text or of the caret.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @param {boolean} enabled `true` when reference picking is on.
 */
export function syncFormulaPickFeedback(
  apiRef: RefObject<GridPrivateApiPremium>,
  enabled: boolean,
): void {
  const editable = enabled ? getActiveFormulaPickEditable(apiRef) : null;
  const handle = editable?.getHandle();
  const selection = handle && !handle.isComposing() ? handle.getSelection() : null;
  if (!editable || !handle || selection === null) {
    applyFormulaPickFeedback(apiRef, false, null);
    return;
  }
  const text = handle.getText();
  const { pending } = apiRef.current.caches.formula!.referencePick;
  const isPending =
    pending !== null &&
    pending.id === editable.ownerCell.id &&
    pending.field === editable.ownerCell.field &&
    isFormulaPendingPickValid(text, selection, pending.pick);
  applyFormulaPickFeedback(
    apiRef,
    getFormulaPickActionForEditable(apiRef, editable, text, selection).type !== 'none',
    isPending ? pending.target : null,
  );
}
