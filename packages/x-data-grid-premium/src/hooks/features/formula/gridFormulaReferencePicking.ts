/**
 * What a pick points at: one cell, or the range between two cells. Shares its
 * shape with the highlight targets, so the picked reference and its rectangle
 * on the grid describe the same thing.
 */
export type FormulaPickTarget = Extract<FormulaReferenceTarget, { kind: 'cell' | 'range' }>;

/**
 * A cell of the grid, as a pick sees it.
 */
export interface FormulaPickCell {
  field: string;
  rowId: GridRowId;
}

export interface PickedReferenceTextOptions {
  /**
   * `true` when the editor shows the A1 dialect.
   * @default false
   */
  a1Notation?: boolean;
}

interface FormulaPickRectangle {
  fromColumn: number;
  toColumn: number;
  fromRow: number;
  toRow: number;
}

/**
 * The positions two cells span, or `null` when one of them cannot be part of a
 * reference: a column without a position (utility, grouping or hidden column)
 * or a row outside the data band (pinned row, autogenerated group or
 * aggregation row, filtered-out row).
 */
function getPickRectangle(
  positionContext: FormulaPositionContext,
  from: FormulaPickCell,
  to: FormulaPickCell,
): FormulaPickRectangle | null {
  const columns = [
    positionContext.getPositionOfField(from.field),
    positionContext.getPositionOfField(to.field),
  ];
  const rows = [
    positionContext.getPositionOfRowId(from.rowId),
    positionContext.getPositionOfRowId(to.rowId),
  ];
  if (columns[0] === undefined || columns[1] === undefined) {
    return null;
  }
  for (const row of rows) {
    if (
      row === undefined ||
      row < positionContext.dataFromIndex ||
      row > positionContext.dataToIndex
    ) {
      return null;
    }
  }
  return {
    fromColumn: Math.min(columns[0], columns[1]),
    toColumn: Math.max(columns[0], columns[1]),
    fromRow: Math.min(rows[0]!, rows[1]!),
    toRow: Math.max(rows[0]!, rows[1]!),
  };
}

/**
 * The target of a pick that starts on `anchor` and ends on `cell`: the cell
 * itself when both are the same, the range between them otherwise. The range
 * goes from its top-left cell to its bottom-right cell, whatever the direction
 * of the gesture, which is also how the reference highlights describe it.
 * `null` when one of the two cells cannot be part of a reference.
 */
export function createFormulaPickTarget(
  positionContext: FormulaPositionContext,
  anchor: FormulaPickCell,
  cell: FormulaPickCell,
): FormulaPickTarget | null {
  const rectangle = getPickRectangle(positionContext, anchor, cell);
  if (rectangle === null) {
    return null;
  }
  if (rectangle.fromColumn === rectangle.toColumn && rectangle.fromRow === rectangle.toRow) {
    return { kind: 'cell', field: cell.field, rowId: cell.rowId };
  }
  return {
    kind: 'range',
    startField: positionContext.getFieldAtPosition(rectangle.fromColumn)!,
    endField: positionContext.getFieldAtPosition(rectangle.toColumn)!,
    startRowId: positionContext.getRowIdAtPosition(rectangle.fromRow)!,
    endRowId: positionContext.getRowIdAtPosition(rectangle.toRow)!,
  };
}

function buildPickedCellText(
  positionContext: FormulaPositionContext,
  ownerCell: { id: GridRowId; field: string },
  target: FormulaPickCell,
  a1Notation: boolean,
): string | null {
  // Row ids compare under string coercion, like the position context and the
  // grid's row lookup.
  const isOwnerRow = String(target.rowId) === String(ownerCell.id);
  if (isOwnerRow && target.field === ownerCell.field) {
    return null;
  }

  const rectangle = getPickRectangle(positionContext, target, target);
  if (rectangle === null) {
    return null;
  }

  if (isOwnerRow) {
    return toFormulaFieldReference(target.field, a1Notation);
  }

  if (a1Notation) {
    return `${columnIndexToLetters(rectangle.fromColumn)}${rectangle.fromRow}`;
  }

  const node: FormulaCellRefNode = {
    type: 'cellRef',
    column: { kind: 'field', field: target.field },
    // The id as the grid holds it (a number stays a number), whatever the
    // caller passed: `ROW(2)` and `ROW("2")` are different texts.
    row: { kind: 'id', id: positionContext.getRowIdAtPosition(rectangle.fromRow)! },
    span: { start: 0, end: 0 },
  };
  return serializeFormulaAst(node);
}

/**
 * The reference text a pick of `target` writes into the formula of
 * `ownerCell`, in the dialect the editor shows — or `null` when the target
 * cannot be referenced that way:
 *
 * - the formula's own cell (a range may cover it: the formula then reports a
 *   circular reference, which the user fixes);
 * - a column without a position (utility, grouping or hidden column);
 * - a row outside the data band (pinned row, autogenerated group or
 *   aggregation row, filtered-out row).
 *
 * A cell in the formula's own row is written as the field name (`price`), in
 * both dialects. Any other cell is written as `B2` in A1 notation and as
 * `REF(COLUMN("price"), ROW(2))` otherwise. A range is written as `B2:C4` in
 * A1 notation and as the `RANGE_REF(…)` that `B2:C4` is stored as otherwise,
 * always from its top-left cell to its bottom-right cell; a range of one cell
 * is written as that cell. The text is relative (no `$`) and reads back to the
 * same cells: A1 text through `toCanonicalFormula`, canonical text through
 * `parseFormula`.
 */
export function buildPickedReferenceText(
  positionContext: FormulaPositionContext,
  ownerCell: { id: GridRowId; field: string },
  target: FormulaPickTarget,
  options: PickedReferenceTextOptions = {},
): string | null {
  const a1Notation = options.a1Notation === true;
  if (target.kind === 'cell') {
    return buildPickedCellText(positionContext, ownerCell, target, a1Notation);
  }

  const rectangle = getPickRectangle(
    positionContext,
    { field: target.startField, rowId: target.startRowId },
    { field: target.endField, rowId: target.endRowId },
  );
  if (rectangle === null) {
    return null;
  }
  if (rectangle.fromColumn === rectangle.toColumn && rectangle.fromRow === rectangle.toRow) {
    return buildPickedCellText(
      positionContext,
      ownerCell,
      { field: target.startField, rowId: target.startRowId },
      a1Notation,
    );
  }

  const from = {
    letters: columnIndexToLetters(rectangle.fromColumn),
    rowNumber: rectangle.fromRow,
  };
  const to = { letters: columnIndexToLetters(rectangle.toColumn), rowNumber: rectangle.toRow };
  if (a1Notation) {
    return `${from.letters}${from.rowNumber}:${to.letters}${to.rowNumber}`;
  }
  // The node an A1 `B2:C4` typed in this cell is stored as, so both dialects
  // pick the same range.
  return serializeFormulaAst(
    buildRangeRefNode(
      { ...from, columnAbsolute: false, rowAbsolute: false },
      { ...to, columnAbsolute: false, rowAbsolute: false },
      0,
      0,
      getRangeFreezeAnchor(positionContext, ownerCell),
    ),
  );
}

/**
 * Grid-aware wrapper of `buildPickedReferenceText`: reads the live position
 * context, and also refuses the single cells the pure builder cannot know
 * about — a cell of an actions column and a cell that is itself being edited.
 * A range may cover such cells.
 */
export function getPickedReferenceText(
  apiRef: RefObject<GridPrivateApiPremium>,
  ownerCell: { id: GridRowId; field: string },
  target: FormulaPickTarget,
  options: PickedReferenceTextOptions = {},
): string | null {
  const text = buildPickedReferenceText(
    gridFormulaA1PositionContextSelector(apiRef),
    ownerCell,
    target,
    options,
  );
  if (text === null || target.kind === 'range') {
    return text;
  }
  if (apiRef.current.getColumn(target.field)?.type === GRID_ACTIONS_COLUMN_TYPE) {
    return null;
  }
  if (apiRef.current.getCellMode(target.rowId, target.field) === GridCellModes.Edit) {
    return null;
  }
  return text;
}

/**
 * What a click on `cell` writes into the formula of `editable`, with the target
 * its rectangle is drawn on, or `null` when the cell cannot be picked.
 *
 * The formula of the computed columns panel belongs to a whole column, so it
 * only reads its own row: the pick is the name of the clicked column, whatever
 * the row, and it is shown on the preview row. The column cannot pick itself.
 */
export function getFormulaPickOfCell(
  apiRef: RefObject<GridPrivateApiPremium>,
  editable: GridFormulaPickEditable,
  cell: FormulaPickCell,
): { reference: string; target: FormulaPickTarget } | null {
  const { ownerCell, a1Notation } = editable;
  if (editable.kind !== 'panel') {
    const target: FormulaPickTarget = { kind: 'cell', ...cell };
    const reference = getPickedReferenceText(apiRef, ownerCell, target, { a1Notation });
    return reference === null ? null : { reference, target };
  }
  // The clicked cell must be one a formula can reference, outside the edited column.
  if (
    cell.field === ownerCell.field ||
    getPickedReferenceText(apiRef, ownerCell, { kind: 'cell', ...cell }) === null
  ) {
    return null;
  }
  return {
    reference: toFormulaFieldReference(cell.field, a1Notation),
    target: { kind: 'cell', field: cell.field, rowId: ownerCell.id },
  };
}

/**
 * The cell a range starts from when the reference `text.slice(start, end)` of
 * the formula is extended: the cell itself for a reference to one cell (a
 * field name is the cell of that column in the row of the formula), the first
 * cell for a range. `null` when the reference does not resolve to cells of the
 * current view (a whole column, a hidden column, a filtered-out row).
 */
export function getFormulaPickAnchor(
  apiRef: RefObject<GridPrivateApiPremium>,
  editable: GridFormulaPickEditable,
  text: string,
  span: { start: number; end: number },
): FormulaPickCell | null {
  // The reference is read on its own: the formula around it may not parse yet.
  const { references } = buildFormulaReferenceModel(
    `=${text.slice(span.start, span.end)}`,
    gridFormulaA1PositionContextSelector(apiRef),
    editable.ownerCell,
    editable.a1Notation,
  );
  const target = references.length === 1 ? references[0].target : null;
  if (target?.kind === 'cell') {
    return { field: target.field, rowId: target.rowId };
  }
  if (target?.kind === 'range') {
    return { field: target.startField, rowId: target.startRowId };
  }
  return null;
}

/**
 * Registers a formula editable as a destination of picked references, for as
 * long as its host is mounted.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @param {GridFormulaPickEditable} editable The editable to register.
 * @returns {() => void} The function that removes the registration.
 */
export function registerFormulaPickEditable(
  apiRef: RefObject<GridPrivateApiPremium>,
  editable: GridFormulaPickEditable,
): () => void {
  const { editables } = apiRef.current.caches.formula!.referencePick;
  editables.add(editable);
  return () => {
    editables.delete(editable);
  };
}

/**
 * The registered editable that holds the DOM focus, which is the one a picked
 * reference is written into.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @returns {GridFormulaPickEditable | null} The focused editable, or `null` when none of them has the focus.
 */
export function getActiveFormulaPickEditable(
  apiRef: RefObject<GridPrivateApiPremium>,
): GridFormulaPickEditable | null {
  for (const editable of apiRef.current.caches.formula!.referencePick.editables) {
    const root = editable.getHandle()?.getRoot();
    if (root && root.ownerDocument.activeElement === root) {
      return editable;
    }
  }
  return null;
}

/**
 * `true` when the props turn reference picking on.
 */
export function isFormulaReferencePickingEnabled(
  props: Pick<
    DataGridPremiumProcessedProps,
    'formulaReferencePicking' | 'disableFormulas' | 'dataSource'
  >,
): boolean {
  return !!props.formulaReferencePicking && !props.disableFormulas && !props.dataSource;
}

/**
 * The pending pick of the session when it belongs to the formula of
 * `editable`, whether or not the next click can still replace it.
 */
export function getFormulaPendingPickOf(
  apiRef: RefObject<GridPrivateApiPremium>,
  editable: GridFormulaPickEditable,
): NonNullable<GridFormulaReferencePickSession['pending']> | null {
  const { pending } = apiRef.current.caches.formula!.referencePick;
  return pending !== null &&
    pending.id === editable.ownerCell.id &&
    pending.field === editable.ownerCell.field
    ? pending
    : null;
}

/**
 * What a click on a cell does to the formula of `editable`, given the text it
 * shows and its selection.
 */
export function getFormulaPickActionForEditable(
  apiRef: RefObject<GridPrivateApiPremium>,
  editable: GridFormulaPickEditable,
  text: string,
  selection: FormulaPickSelection,
  mode: FormulaPickMode = 'replace',
): FormulaPickAction {
  const { a1Notation } = editable;
  if (editable.kind === 'panel' && text.trim() === '') {
    // A cleared formula of the panel takes the reference, behind a new `=`.
    return { type: 'replace', start: 0, end: text.length };
  }
  return getFormulaPickAction(
    text,
    selection,
    getFormulaPendingPickOf(apiRef, editable)?.pick ?? null,
    {
      a1Notation,
      // The panel builds no range: Shift+click is a plain click there.
      mode: editable.kind === 'panel' && mode === 'extend' ? 'replace' : mode,
      // A bare name is a reference when it is the name a click on that column writes.
      isFieldName: (name) =>
        apiRef.current.getColumn(name) != null &&
        toFormulaFieldReference(name, a1Notation) === name,
    },
  );
}

/**
 * Shows where the picking session stands:
 *
 * - the root class that gives the cells their picking cursor, while a click
 *   on a cell would write a reference;
 * - the pending reference, whose rectangle the overlay draws solid.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @param {boolean} pickable `true` when a click on a cell would write a reference.
 * @param {FormulaReferenceTarget | null} pendingReference The target of the pending reference.
 */
export function applyFormulaPickFeedback(
  apiRef: RefObject<GridPrivateApiPremium>,
  pickable: boolean,
  pendingReference: FormulaReferenceTarget | null,
): void {
  // Always re-applied: a render of the root with new classes drops a class set here.
  apiRef.current.rootElementRef?.current?.classList.toggle(
    gridClasses['root--formulaReferencePicking'],
    pickable,
  );

  const activeEdit = gridFormulaActiveEditSelector(apiRef);
  if (activeEdit === null || (activeEdit.pendingReference ?? null) === pendingReference) {
    return;
  }
  apiRef.current.setState((state) => {
    if (state.formula.activeEdit === null) {
      return state;
    }
    return {
      ...state,
      formula: {
        ...state.formula,
        activeEdit: {
          ...state.formula.activeEdit,
          pendingReference: pendingReference ?? undefined,
        },
      },
    };
  });
}

/**
 * Ends the picking session: the gesture and the pending reference are
 * forgotten, and the feedback is removed. Called when the edit, or the draft of
 * the formula bar, that the session belongs to ends.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 */
export function clearFormulaPickSession(apiRef: RefObject<GridPrivateApiPremium>): void {
  const session = apiRef.current.caches.formula!.referencePick;
  if (session.gesture === 'down') {
    // The edit ended in the middle of a picking drag.
    apiRef.current.rootElementRef?.current?.classList.remove(
      gridClasses['root--disableUserSelection'],
    );
  }
  session.gesture = null;
  session.pending = null;
  applyFormulaPickFeedback(apiRef, false, null);
}

/**
 * Recomputes the picking feedback from the focused editable: its text and its
 * caret decide whether a click would write a reference, and whether the
 * reference of the last pick is still pending. Called after every change of
 * the text or of the caret.
 * @param {RefObject<GridPrivateApiPremium>} apiRef The private grid api.
 * @param {boolean} enabled `true` when reference picking is on.
 */
export function syncFormulaPickFeedback(
  apiRef: RefObject<GridPrivateApiPremium>,
  enabled: boolean,
): void {
  const editable = enabled ? getActiveFormulaPickEditable(apiRef) : null;
  const handle = editable?.getHandle();
  const selection = handle && !handle.isComposing() ? handle.getSelection() : null;
  if (!editable || !handle || selection === null) {
    applyFormulaPickFeedback(apiRef, false, null);
    return;
  }
  const text = handle.getText();
  const pending = getFormulaPendingPickOf(apiRef, editable);
  applyFormulaPickFeedback(
    apiRef,
    getFormulaPickActionForEditable(apiRef, editable, text, selection).type !== 'none',
    pending !== null && isFormulaPendingPickValid(text, selection, pending.pick)
      ? pending.target
      : null,
  );
}
