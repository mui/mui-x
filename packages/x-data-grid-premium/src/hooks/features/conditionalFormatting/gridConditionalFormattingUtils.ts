/**
 * Rules restored from untrusted data may not have the expected shape,
 * and rules saved by a newer version may have an unknown `type`.
 */
export const isConditionalFormattingHighlightRule = (
  rule: unknown,
): rule is GridConditionalFormattingHighlightRule =>
  typeof rule === 'object' &&
  rule !== null &&
  (rule as GridConditionalFormattingHighlightRule).type === 'highlight' &&
  Array.isArray((rule as GridConditionalFormattingHighlightRule).fields) &&
  isGridCellCondition((rule as GridConditionalFormattingHighlightRule).condition);

const HEX_COLOR = /^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i;

const sanitizeColor = (color: unknown): string | undefined => {
  if (color === undefined) {
    return undefined;
  }
  if (typeof color === 'string' && HEX_COLOR.test(color)) {
    return color;
  }
  if (process.env.NODE_ENV !== 'production') {
    warnOnce(
      `MUI X Data Grid: The conditional formatting color ${JSON.stringify(color)} is ignored. Use a hex color like "#ff0000".`,
    );
  }
  return undefined;
};

/**
 * Keeps the known properties with a valid value: the style comes from the
 * model, which can be restored from untrusted data, and ends up in a stylesheet.
 */
export function sanitizeConditionalFormattingStyle(
  style: GridConditionalFormattingStyle | undefined,
): GridConditionalFormattingStyle {
  const result: GridConditionalFormattingStyle = {};
  if (style == null) {
    return result;
  }
  const color = sanitizeColor(style.color);
  if (color !== undefined) {
    result.color = color;
  }
  const backgroundColor = sanitizeColor(style.backgroundColor);
  if (backgroundColor !== undefined) {
    result.backgroundColor = backgroundColor;
  }
  if (style.fontWeight === 'bold') {
    result.fontWeight = 'bold';
  }
  if (style.fontStyle === 'italic') {
    result.fontStyle = 'italic';
  }
  if (style.textDecoration === 'underline' || style.textDecoration === 'line-through') {
    result.textDecoration = style.textDecoration;
  }
  return result;
}

export const getConditionalFormattingClassName = (instanceId: number, index: number) =>
  `MuiDataGrid-conditionalFormatting-${instanceId}-${index}`;

const toHexDigits = (color: string) =>
  color.length === 4
    ? color
        .slice(1)
        .split('')
        .map((char) => char + char)
        .join('')
    : color.slice(1);

/**
 * Black or white, whichever has the higher contrast ratio with the background.
 */
export const getContrastTextColor = (backgroundColor: string) =>
  getContrastRatio(backgroundColor, '#000000') >= getContrastRatio(backgroundColor, '#ffffff')
    ? '#000000'
    : '#ffffff';

/**
 * The global styles of the rules. The first rule is written last so it wins
 * when several rules set the same property. The background skips selected
 * cells and rows, so the selection stays visible.
 * A rule with a background and no text color gets a readable one, so it works in
 * light and dark mode. It is written first and without specificity, so any rule
 * that sets a text color wins.
 */
export function getConditionalFormattingStyles(
  model: GridConditionalFormattingModel,
  instanceId: number,
) {
  type Styles = Record<
    string,
    Omit<GridConditionalFormattingStyle, 'fontWeight'> & { fontWeight?: string }
  >;
  const contrastStyles: Styles = {};
  const styles: Styles = {};
  for (let i = model.length - 1; i >= 0; i -= 1) {
    const rule = model[i];
    if (!isConditionalFormattingHighlightRule(rule)) {
      continue;
    }
    const { backgroundColor, ...textStyle } = sanitizeConditionalFormattingStyle(rule.style);
    const cell = `.${gridClasses.cell}.${getConditionalFormattingClassName(instanceId, i)}`;
    if (Object.keys(textStyle).length > 0) {
      styles[`.${gridClasses.root} ${cell}`] = textStyle;
    }
    if (backgroundColor !== undefined) {
      styles[
        `.${gridClasses.root} .${gridClasses.row}:not(.Mui-selected) > ${cell}:not(.Mui-selected)`
      ] = { backgroundColor };
      if (textStyle.color === undefined) {
        contrastStyles[
          `.${gridClasses.root} ${cell}:where(.${gridClasses.row}:not(.Mui-selected) > :not(.Mui-selected))`
        ] = { color: getContrastTextColor(backgroundColor) };
      }
    }
  }
  return { ...contrastStyles, ...styles };
}

const toArgb = (color: string) => `FF${toHexDigits(color).toUpperCase()}`;

export function getConditionalFormattingExcelStyle(
  style: GridConditionalFormattingStyle,
): Partial<Style> | null {
  const { color, backgroundColor, fontWeight, fontStyle, textDecoration } =
    sanitizeConditionalFormattingStyle(style);
  const excelStyle: Partial<Style> = {};
  const font: Partial<Style['font']> = {};
  if (color !== undefined) {
    font.color = { argb: toArgb(color) };
  }
  if (fontWeight === 'bold') {
    font.bold = true;
  }
  if (fontStyle === 'italic') {
    font.italic = true;
  }
  if (textDecoration === 'underline') {
    font.underline = true;
  }
  if (textDecoration === 'line-through') {
    font.strike = true;
  }
  if (Object.keys(font).length > 0) {
    excelStyle.font = font;
  }
  if (backgroundColor !== undefined) {
    // Conditional formats read the solid fill color from `bgColor`.
    const argb = toArgb(backgroundColor);
    excelStyle.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb }, bgColor: { argb } };
  }
  return Object.keys(excelStyle).length > 0 ? excelStyle : null;
}

export interface ConditionalFormattingExcelLayout {
  fieldToColumnLetter: Map<string, string>;
  fieldToColumnType: Map<string, string | undefined>;
  /**
   * The first and last Excel rows of each run of formatted rows.
   */
  rowRuns: [number, number][];
}

/**
 * One Excel conditional format per rule, exported column and run of rows, with
 * the formula written for the top-left cell of the range. Rules that cannot be
 * exported are skipped.
 * @param {GridConditionalFormattingModel} model The rules.
 * @param {ConditionalFormattingExcelLayout} layout Where the exported columns and rows are.
 * @param {Function} getFormulaExcelFormula Converts the formula of a `formula` condition.
 * @returns {ConditionalFormattingOptions[]} The conditional formats to add to the worksheet.
 */
export function getConditionalFormattingExcelOptions(
  model: GridConditionalFormattingModel,
  layout: ConditionalFormattingExcelLayout,
  getFormulaExcelFormula:
    | ((
        formula: string,
        fieldToColumnLetter: Map<string, string>,
        rowNumber: number,
      ) => string | null)
    | undefined,
): ConditionalFormattingOptions[] {
  const { fieldToColumnLetter, fieldToColumnType, rowRuns } = layout;
  const options: ConditionalFormattingOptions[] = [];
  model.forEach((rule, index) => {
    if (!isConditionalFormattingHighlightRule(rule)) {
      return;
    }
    const style = getConditionalFormattingExcelStyle(rule.style);
    if (style === null) {
      return;
    }
    const { condition } = rule;
    for (const [firstRowNumber, lastRowNumber] of rowRuns) {
      // Only reads other columns: the same formula for every column.
      const sharedFormula =
        condition.type === 'formula'
          ? (getFormulaExcelFormula?.(condition.formula, fieldToColumnLetter, firstRowNumber) ??
            null)
          : null;
      for (const field of rule.fields) {
        const letter = fieldToColumnLetter.get(field);
        if (letter === undefined) {
          continue;
        }
        const cell = `${letter}${firstRowNumber}`;
        const formula =
          condition.type === 'formula'
            ? sharedFormula
            : getGridCellConditionExcelFormula(condition, cell, fieldToColumnType.get(field));
        if (formula === null) {
          continue;
        }
        options.push({
          ref: `${cell}:${letter}${lastRowNumber}`,
          rules: [{ type: 'expression', priority: index + 1, formulae: [formula], style }],
        });
      }
    }
  });
  return options;
}

/**
 * Row grouping and aggregation rows are generated and have no value of their own to format.
 * Tree data parents are real rows.
 */
export const isConditionalFormattingRow = (
  apiRef: RefObject<GridPrivateApiPremium>,
  id: GridRowId,
) => {
  const type = gridRowNodeSelector(apiRef, id)?.type;
  if (type !== 'leaf' && type !== 'pinnedRow' && type !== 'group') {
    return false;
  }
  // The root aggregation row is a pinned row, and row grouping groups are generated.
  const row = apiRef.current.getRow(id);
  return row != null && !isAutogeneratedRow(row);
};

/**
 * The value a `cell` or `text` condition reads: the one the Excel export writes,
 * so the formats agree once exported.
 */
export function getConditionalFormattingCellValue(
  apiRef: RefObject<GridPrivateApiPremium>,
  row: GridValidRowModel,
  id: GridRowId,
  field: string,
): unknown {
  const colDef = gridColumnLookupSelector(apiRef)[field];
  if (colDef === undefined) {
    return undefined;
  }
  switch (colDef.type) {
    case 'number':
    case 'boolean':
    case 'date':
    case 'dateTime':
      return apiRef.current.getCellValue(id, field);
    default: {
      const formattedValue = apiRef.current.getRowFormattedValue(row, colDef);
      return typeof formattedValue === 'object' &&
        formattedValue !== null &&
        'label' in formattedValue
        ? formattedValue.label
        : formattedValue;
    }
  }
}

// `columnIndexToLetters` lives in the formula engine, which is not bundled.
const toColumnLetters = (index: number) => {
  let letters = '';
  for (let rest = index + 1; rest > 0; rest = Math.floor((rest - 1) / 26)) {
    letters = String.fromCharCode(65 + ((rest - 1) % 26)) + letters;
  }
  return letters;
};

/**
 * The conditional formats of an export whose rows start at `firstDataRowNumber`.
 */
export function getConditionalFormattingExcelExport(
  apiRef: RefObject<GridPrivateApiPremium>,
  columns: GridStateColDef[],
  rowIds: GridRowId[],
  firstDataRowNumber: number,
): ConditionalFormattingOptions[] {
  const model = gridConditionalFormattingSelector(apiRef);
  if (model.length === 0) {
    return [];
  }
  const rowRuns: [number, number][] = [];
  rowIds.forEach((id, index) => {
    if (!isConditionalFormattingRow(apiRef, id)) {
      return;
    }
    const rowNumber = firstDataRowNumber + index;
    const lastRun = rowRuns[rowRuns.length - 1];
    if (lastRun !== undefined && lastRun[1] === rowNumber - 1) {
      lastRun[1] = rowNumber;
    } else {
      rowRuns.push([rowNumber, rowNumber]);
    }
  });
  return getConditionalFormattingExcelOptions(
    model,
    {
      fieldToColumnLetter: new Map(
        columns.map((column, index) => [column.field, toColumnLetters(index)]),
      ),
      fieldToColumnType: new Map(columns.map((column) => [column.field, column.type])),
      rowRuns,
    },
    apiRef.current.getCellFormulaConditionExcelFormula,
  );
}
