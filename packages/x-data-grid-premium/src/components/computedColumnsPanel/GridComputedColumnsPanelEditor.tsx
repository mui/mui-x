type EditorFormatDraft = Pick<EditorDraft, 'formatStyle' | 'currency' | 'decimals' | 'grouping'>;

/**
 * What the format controls show for a stored `numberFormat`. The controls are
 * coarser than the options (one Decimals field for both fraction bounds), so
 * the seed is also what `buildNumberFormat` compares the draft to: a control
 * still equal to its seed was not touched.
 */
function createFormatSeed(numberFormat: Intl.NumberFormatOptions | undefined): EditorFormatDraft {
  const style = numberFormat?.style;
  return {
    formatStyle: style === 'percent' || style === 'currency' ? style : 'decimal',
    currency: numberFormat?.currency ?? 'USD',
    decimals:
      numberFormat?.maximumFractionDigits === undefined
        ? ''
        : String(numberFormat.maximumFractionDigits),
    grouping: numberFormat?.useGrouping !== false,
  };
}

function createDraft(definition: GridComputedColumnDefinition | null): EditorDraft {
  return {
    headerName: definition?.headerName ?? '',
    field: definition?.field ?? '',
    // A new formula starts with the `=`, so the autocomplete opens right away.
    formula: definition?.formula ?? '=',
    type: definition?.type ?? 'number',
    ...createFormatSeed(definition?.numberFormat),
  };
}

function normalizeFormula(text: string): string {
  const trimmed = text.trim();
  if (trimmed === '' || isFormulaSource(trimmed)) {
    return trimmed;
  }
  return `=${trimmed}`;
}

function parseDecimals(decimals: string): number | null | undefined {
  if (decimals.trim() === '') {
    return undefined;
  }
  const value = Number(decimals);
  if (!Number.isInteger(value) || value < 0 || value > MAX_FRACTION_DIGITS) {
    return null;
  }
  return value;
}

/**
 * The `numberFormat` of the draft. The editor manages three groups of options
 * (style + currency, the fraction bounds, the grouping): a group the user
 * changed replaces the stored options of that group, an untouched one keeps
 * them as stored (a stored `{ minimumFractionDigits: 0, maximumFractionDigits: 2 }`
 * is not what the single Decimals field would write). Anything else in a
 * stored format is kept.
 */
function buildNumberFormat(
  draft: EditorDraft,
  stored: Intl.NumberFormatOptions | undefined,
): Intl.NumberFormatOptions | undefined {
  if (draft.type !== 'number') {
    return undefined;
  }
  const seed = createFormatSeed(stored);
  const options: Intl.NumberFormatOptions = { ...stored };
  if (draft.formatStyle !== seed.formatStyle || draft.currency !== seed.currency) {
    delete options.style;
    delete options.currency;
    if (draft.formatStyle !== 'decimal') {
      options.style = draft.formatStyle;
    }
    if (draft.formatStyle === 'currency') {
      options.currency = draft.currency.toUpperCase();
    }
  }
  if (draft.decimals !== seed.decimals) {
    delete options.minimumFractionDigits;
    delete options.maximumFractionDigits;
    const decimals = parseDecimals(draft.decimals);
    if (typeof decimals === 'number') {
      options.minimumFractionDigits = decimals;
      options.maximumFractionDigits = decimals;
    }
  }
  if (draft.grouping !== seed.grouping) {
    delete options.useGrouping;
    if (!draft.grouping) {
      options.useGrouping = false;
    }
  }
  return Object.keys(options).length === 0 ? undefined : options;
}

/**
 * The stored shape of a draft: optional properties are left out when they have no value.
 */
function buildDefinition(
  draft: EditorDraft,
  stored: GridComputedColumnDefinition | null,
): GridComputedColumnDefinition {
  const definition: GridComputedColumnDefinition = {
    field: draft.field.trim(),
    headerName: draft.headerName.trim(),
    formula: normalizeFormula(draft.formula),
    type: draft.type,
  };
  const numberFormat = buildNumberFormat(draft, stored?.numberFormat);
  if (numberFormat !== undefined) {
    definition.numberFormat = numberFormat;
  }
  if (stored?.description !== undefined) {
    definition.description = stored.description;
  }
  return definition;
}

function isFormatInvalid(draft: EditorDraft): { currency: boolean; decimals: boolean } {
  const isNumber = draft.type === 'number';
  return {
    currency:
      isNumber && draft.formatStyle === 'currency' && !CURRENCY_CODE_REGEX.test(draft.currency),
    decimals: isNumber && parseDecimals(draft.decimals) === null,
  };
}

/**
 * Whether the formula `activeEdit` is the editor's own (a draft for its field —
 * a cell editor carries no draft, the formula bar's draft targets a data cell).
 */
function ownsActiveEdit(edit: GridFormulaActiveEdit | null, field: string | null): boolean {
  return edit !== null && edit.draft !== undefined && field !== null && edit.field === field;
}

function inferColumnType(value: unknown): GridComputedColumnType | null {
  if (typeof value === 'number') {
    return 'number';
  }
  if (typeof value === 'string') {
    return 'string';
  }
  if (typeof value === 'boolean') {
    return 'boolean';
  }
  if (value instanceof Date) {
    const hasTime =
      value.getHours() !== 0 ||
      value.getMinutes() !== 0 ||
      value.getSeconds() !== 0 ||
      value.getMilliseconds() !== 0;
    return hasTime ? 'dateTime' : 'date';
  }
  return null;
}

/**
 * The editor view of the computed columns panel: a local draft of one
 * definition (name, field, formula, result type and number format), validated
 * on every change, with a debounced preview of the formula on one row. The
 * draft only reaches the model on Apply; unmounting discards it.
 */
function GridComputedColumnsPanelEditor(props: GridComputedColumnsPanelEditorProps) {
  const { session, onDone } = props;
  const apiRef = useGridPrivateApiContext();
  const rootProps = useGridRootProps();
  const classes = useUtilityClasses(rootProps);
  const id = React.useId();
  const editableRef = React.useRef<GridFormulaEditableHandle | null>(null);
  const nameInputRef = React.useRef<HTMLInputElement | null>(null);

  const storedDefinition = session.definition;
  const isEditing = storedDefinition !== null;
  const a1Notation = Boolean(rootProps.formulaA1Notation);

  const [draft, setDraft] = React.useState<EditorDraft>(() => createDraft(storedDefinition));
  // The derived field stops following the name once the user edits it.
  const [fieldTouched, setFieldTouched] = React.useState(isEditing);
  // The result type stops following the preview once the user picks one.
  const [typeTouched, setTypeTouched] = React.useState(isEditing);
  const [dirty, setDirty] = React.useState(false);

  const updateDraft = React.useCallback((changes: Partial<EditorDraft>) => {
    setDraft((prev) => ({ ...prev, ...changes }));
    setDirty(true);
  }, []);

  // ----- Preview row (follows the focused cell) -----

  const isDataRow = React.useCallback(
    (rowId: GridRowId) => {
      const row = apiRef.current.getRow(rowId);
      return row != null && !isAutogeneratedRow(row);
    },
    [apiRef],
  );

  const focusedCell = useGridSelector(apiRef, gridFocusCellSelector);
  const expandedSortedRowIds = useGridSelector(apiRef, gridExpandedSortedRowIdsSelector);

  const [previewRowId, setPreviewRowId] = React.useState<GridRowId | null>(() => {
    if (session.sampleRowId !== undefined && isDataRow(session.sampleRowId)) {
      return session.sampleRowId;
    }
    if (focusedCell !== null && isDataRow(focusedCell.id)) {
      return focusedCell.id;
    }
    return expandedSortedRowIds.find(isDataRow) ?? null;
  });

  // Only a focus MOVE after the editor opened changes the preview row (the
  // request's sample row wins over a cell focused earlier). Focus leaving the
  // cells keeps the last row.
  const lastFocusedCellRef = React.useRef(focusedCell);
  React.useEffect(() => {
    if (focusedCell === lastFocusedCellRef.current) {
      return;
    }
    lastFocusedCellRef.current = focusedCell;
    if (focusedCell !== null && isDataRow(focusedCell.id)) {
      setPreviewRowId(focusedCell.id);
    }
  }, [focusedCell, isDataRow]);

  // A preview row removed from the grid falls back to the first data row; so
  // does an editor opened on an empty grid once rows arrive (`null` → `null`
  // is a no-op, the effect cannot loop).
  React.useEffect(() => {
    if (previewRowId === null || apiRef.current.getRow(previewRowId) == null) {
      setPreviewRowId(expandedSortedRowIds.find(isDataRow) ?? null);
    }
  }, [apiRef, expandedSortedRowIds, previewRowId, isDataRow]);

  const previewRowIndex = React.useMemo(() => {
    if (previewRowId === null) {
      return null;
    }
    const index = expandedSortedRowIds.indexOf(previewRowId);
    return index === -1 ? null : index + 1;
  }, [expandedSortedRowIds, previewRowId]);

  // ----- Draft definition + validation -----

  const draftDefinition = React.useMemo<GridComputedColumnDefinition>(
    () => buildDefinition(draft, storedDefinition),
    [draft, storedDefinition],
  );

  // The verdict is read from the columns state (fields taken or freed, referenced columns
  // removed): it follows every hydration, so an undo/redo under the editor shows up without
  // a keystroke.
  const columnLookup = useGridSelector(apiRef, gridColumnLookupSelector);
  const validation = React.useMemo<GridComputedColumnValidationResult>(
    () =>
      apiRef.current.validateComputedColumnDefinition!(
        draftDefinition,
        isEditing ? { ignoreField: storedDefinition.field } : undefined,
      ),
    // eslint-disable-next-line react-hooks/exhaustive-deps -- `columnLookup` is read through the state
    [apiRef, columnLookup, draftDefinition, isEditing, storedDefinition],
  );

  const { currency: currencyInvalid, decimals: decimalsInvalid } = isFormatInvalid(draft);
  const canApply = validation.valid && !currencyInvalid && !decimalsInvalid;
  const showValidation = (dirty || isEditing) && validation.issues.length > 0;

  // ----- Preview (debounced, through the cell path) -----

  const [rawPreview, setRawPreview] = React.useState<GridFormulaResult | null>(null);
  const expression = getFormulaExpression(draftDefinition.formula).trim();
  const ownerField = draftDefinition.field === '' ? DRAFT_FIELD_PLACEHOLDER : draftDefinition.field;

  const computePreview = React.useCallback(
    (rowId: GridRowId) =>
      previewFormulaResult(apiRef, { id: rowId, field: ownerField }, `=${expression}`, {
        a1Notation,
      }),
    [apiRef, expression, ownerField, a1Notation],
  );

  // What the result depends on besides the draft, none of which a render of the
  // editor tells by itself:
  // - the data of the preview row (`updateRows`, a replaced `rows` prop) — the
  //   row-scoped selector ignores the updates of the other rows;
  // - the revision: the getters of the referenced columns (computed or not) and
  //   the function registry;
  // - a formula cell of the preview row re-evaluated: the row object is not
  //   touched, and the revision only follows the fields the STORED computed
  //   columns reference.
  const previewRow = useGridSelector(apiRef, gridRowSelector, previewRowId as GridRowId);
  const revision = useGridSelector(apiRef, gridComputedColumnsRevisionSelector);
  const [evaluationTick, setEvaluationTick] = React.useState(0);
  const handleFormulaEvaluated: GridEventListener<'formulaEvaluated'> = ({ changedCells }) => {
    if (previewRowId !== null && changedCells.some((cell) => cell.id === previewRowId)) {
      setEvaluationTick((prev) => prev + 1);
    }
  };
  useGridEvent(apiRef, 'formulaEvaluated', handleFormulaEvaluated);

  React.useEffect(() => {
    if (previewRowId === null || expression === '') {
      setRawPreview(null);
      return undefined;
    }
    const timer = setTimeout(() => {
      setRawPreview(computePreview(previewRowId));
    }, PREVIEW_DEBOUNCE_MS);
    return () => clearTimeout(timer);
  }, [previewRowId, expression, computePreview, previewRow, revision, evaluationTick]);

  React.useEffect(() => {
    if (typeTouched || rawPreview === null || rawPreview.type === 'error') {
      return;
    }
    const inferred = inferColumnType(rawPreview.value);
    if (inferred !== null) {
      setDraft((prev) => (prev.type === inferred ? prev : { ...prev, type: inferred }));
    }
  }, [rawPreview, typeTouched]);

  // The same formatter the cell will use (number format, date/boolean
  // formatting). A format still being typed (an incomplete currency code)
  // would make `Intl.NumberFormat` throw: it is left out until it is valid.
  const previewFormatValid = !currencyInvalid && !decimalsInvalid;
  const previewColDef = React.useMemo<GridColDef>(() => {
    const { numberFormat, ...definition } = draftDefinition;
    return createComputedBaseColDef(
      {
        ...definition,
        field: ownerField,
        ...(previewFormatValid && numberFormat !== undefined ? { numberFormat } : {}),
      },
      NOOP_GETTERS as never,
    );
  }, [draftDefinition, ownerField, previewFormatValid]);

  const preview = React.useMemo(() => {
    if (rawPreview === null || previewRowId === null) {
      return null;
    }
    const result = coerceComputedResult(rawPreview, draftDefinition.type);
    if (result.type === 'error') {
      return { text: result.code, error: true };
    }
    if (result.value === null) {
      return { text: '', error: false };
    }
    const row = apiRef.current.getRow(previewRowId) ?? {};
    let formatted: unknown;
    try {
      formatted = previewColDef.valueFormatter!(result.value as never, row, previewColDef, apiRef);
    } catch {
      formatted = result.value;
    }
    return { text: formatted == null ? '' : String(formatted), error: false };
  }, [apiRef, rawPreview, previewRowId, draftDefinition.type, previewColDef]);

  // The parse error's span, shifted from the normalized source to the text the
  // editable displays (leading whitespace, a missing `=`); shown with the
  // validation list.
  const errorSpans = React.useMemo<FormulaSourceSpan[]>(() => {
    if (!showValidation) {
      return EMPTY_SPANS;
    }
    const trimmed = draft.formula.trim();
    const delta = draft.formula.indexOf(trimmed) - (isFormulaSource(trimmed) ? 0 : 1);
    const spans = validation.issues.flatMap((issue) => {
      if (issue.code !== 'parseError' || issue.span === undefined) {
        return [];
      }
      const start = issue.span.start + delta;
      const end = issue.span.end + delta;
      // An empty span (unexpected end of the formula) underlines the character before it.
      return [start < end ? { start, end } : { start: Math.max(0, start - 1), end: start }];
    });
    return spans.length === 0 ? EMPTY_SPANS : spans;
  }, [showValidation, validation.issues, draft.formula]);

  // ----- In-grid outlines of the referenced cells of the preview row -----

  // The editor publishes its draft as the formula `activeEdit` — the reference
  // overlay outlines the referenced cells of the preview row from it. It
  // yields to a cell editor or a formula bar draft (theirs carries another
  // field) and reclaims once they clear it (the bar clears any draft on every
  // cell focus move, `cellEditStop` clears unconditionally).
  const activeEdit = useGridSelector(apiRef, gridFormulaActiveEditSelector);
  // The field last published: the draft field follows the name of a new column,
  // so the editor's own entry can carry a previous field.
  const publishedFieldRef = React.useRef<string | null>(null);
  React.useEffect(() => {
    if (previewRowId === null) {
      return;
    }
    if (
      activeEdit !== null &&
      !ownsActiveEdit(activeEdit, ownerField) &&
      !ownsActiveEdit(activeEdit, publishedFieldRef.current)
    ) {
      return;
    }
    publishedFieldRef.current = ownerField;
    apiRef.current.setFormulaActiveEdit!({
      id: previewRowId,
      field: ownerField,
      draft: draft.formula,
    });
  }, [apiRef, activeEdit, previewRowId, ownerField, draft.formula]);

  React.useEffect(() => {
    const api = apiRef.current;
    return () => {
      if (ownsActiveEdit(gridFormulaActiveEditSelector(apiRef), publishedFieldRef.current)) {
        api.setFormulaActiveEdit!(null);
      }
    };
  }, [apiRef]);

  // ----- Handlers -----

  const handleNameChange = React.useCallback(
    (event: React.ChangeEvent<HTMLInputElement>) => {
      const headerName = event.target.value;
      if (fieldTouched) {
        updateDraft({ headerName });
        return;
      }
      const existingFields = new Set<string>(Object.keys(gridColumnLookupSelector(apiRef)));
      gridComputedColumnsSelector(apiRef).forEach((definition) =>
        existingFields.add(definition.field),
      );
      updateDraft({
        headerName,
        field:
          headerName.trim() === '' ? '' : deriveComputedColumnField(headerName, existingFields),
      });
    },
    [apiRef, fieldTouched, updateDraft],
  );

  const handleFieldChange = React.useCallback(
    (event: React.ChangeEvent<HTMLInputElement>) => {
      setFieldTouched(true);
      updateDraft({ field: event.target.value });
    },
    [updateDraft],
  );

  const handleFormulaChange = React.useCallback(
    (text: string) => {
      updateDraft({ formula: text });
    },
    [updateDraft],
  );

  const handleTypeChange = React.useCallback(
    (event: React.ChangeEvent<HTMLSelectElement>) => {
      setTypeTouched(true);
      updateDraft({ type: event.target.value as GridComputedColumnType });
    },
    [updateDraft],
  );

  const handleApply = React.useCallback(() => {
    if (!canApply) {
      return;
    }
    let definition = draftDefinition;
    // The type follows the debounced preview: an Apply faster than the debounce
    // resolves it from the formula as it is now, not as it was 150 ms ago.
    if (!typeTouched && previewRowId !== null && expression !== '') {
      const result = computePreview(previewRowId);
      const inferred =
        result === null || result.type === 'error' ? null : inferColumnType(result.value);
      if (inferred !== null && inferred !== draft.type) {
        const finalDraft = { ...draft, type: inferred };
        definition = buildDefinition(finalDraft, storedDefinition);
        const formatInvalid = isFormatInvalid(finalDraft);
        if (
          formatInvalid.currency ||
          formatInvalid.decimals ||
          !apiRef.current.validateComputedColumnDefinition!(
            definition,
            isEditing ? { ignoreField: storedDefinition.field } : undefined,
          ).valid
        ) {
          // The new type brings back format fields that were hidden (and not
          // checked): show them instead of saving what the user cannot see.
          setDraft(finalDraft);
          return;
        }
      }
    }
    const { field } = definition;
    if (isEditing) {
      apiRef.current.updateComputedColumn(storedDefinition.field, {
        // `updateComputedColumn` merges: a format removed by the editor is cleared explicitly.
        numberFormat: undefined,
        ...definition,
      });
    } else {
      apiRef.current.addComputedColumn(definition, { columnIndex: session.columnIndex });
    }
    onDone({ type: 'applied', field });
  }, [
    apiRef,
    canApply,
    computePreview,
    draft,
    draftDefinition,
    expression,
    isEditing,
    onDone,
    previewRowId,
    session.columnIndex,
    storedDefinition,
    typeTouched,
  ]);

  const handleDelete = React.useCallback(() => {
    if (isEditing) {
      apiRef.current.removeComputedColumn(storedDefinition.field);
    }
    onDone({ type: 'deleted' });
  }, [apiRef, isEditing, onDone, storedDefinition]);

  const handleCancel = React.useCallback(() => {
    onDone({ type: 'cancelled' });
  }, [onDone]);

  const handleInputKeyDown = React.useCallback(
    (event: React.KeyboardEvent<HTMLInputElement>) => {
      // An Enter that confirms an IME composition belongs to the IME.
      if (isComposingKeyEvent(event)) {
        return;
      }
      if (event.key === 'Enter') {
        event.preventDefault();
        handleApply();
      }
    },
    [handleApply],
  );

  // Ctrl/Cmd+Enter applies from any field. Captured before the field sees it:
  // a select would open its menu on Enter, the editable would accept a
  // suggestion.
  const handleRootKeyDownCapture = React.useCallback(
    (event: React.KeyboardEvent<HTMLDivElement>) => {
      if (isComposingKeyEvent(event)) {
        return;
      }
      if (event.key === 'Enter' && (event.ctrlKey || event.metaKey)) {
        event.preventDefault();
        event.stopPropagation();
        handleApply();
      }
    },
    [handleApply],
  );

  // Escape cancels unless a field consumed it: the editable's popup and the
  // select menus stop their own Escape, the reference search clears itself first.
  const handleRootKeyDown = React.useCallback(
    (event: React.KeyboardEvent<HTMLDivElement>) => {
      // An Escape that cancels an IME composition does not cancel the editor.
      if (isComposingKeyEvent(event)) {
        return;
      }
      if (event.key === 'Escape' && !event.defaultPrevented) {
        event.preventDefault();
        handleCancel();
        return;
      }
      // Home/End with the caret already at that edge of the formula: the
      // browser would otherwise scroll the panel body instead (and away from
      // the formula).
      if ((event.key === 'End' || event.key === 'Home') && !event.defaultPrevented) {
        const editable = editableRef.current;
        const root = editable?.getRoot();
        if (root && root.contains(event.target as Node)) {
          const caret = editable!.getCaret();
          const edge = event.key === 'End' ? (root.textContent ?? '').length : 0;
          if (caret === edge) {
            event.preventDefault();
          }
        }
      }
    },
    [handleCancel],
  );

  const handleInsert = React.useCallback(
    (text: string, event: React.SyntheticEvent) => {
      const editable = editableRef.current;
      if (!editable) {
        return;
      }
      // A cleared formula gets its `=` back with the first inserted token.
      editable.insertText(draft.formula.trim() === '' ? `=${text}` : text, event);
      editable.focus();
    },
    [draft.formula],
  );

  // Clicking the formula surface around the editable focuses it (like an input's padding).
  const handleFormulaSurfaceMouseDown = React.useCallback(
    (event: React.MouseEvent<HTMLDivElement>) => {
      const root = editableRef.current?.getRoot();
      if (root && !root.contains(event.target as Node)) {
        event.preventDefault();
        editableRef.current?.focus();
        editableRef.current?.placeCaret(null);
      }
    },
    [],
  );

  // Focus on open: the name of a new column, the formula of an existing one.
  React.useEffect(() => {
    if (isEditing) {
      editableRef.current?.focus();
      editableRef.current?.placeCaret(null);
    } else {
      nameInputRef.current?.focus();
    }
  }, [isEditing]);

  const getLocaleText = apiRef.current.getLocaleText;
  const nameId = `${id}-name`;
  const fieldId = `${id}-field`;
  const formulaLabelId = `${id}-formula-label`;
  const typeId = `${id}-type`;
  const typeLabelId = `${id}-type-label`;
  const styleId = `${id}-style`;
  const styleLabelId = `${id}-style-label`;
  const previewLabelId = `${id}-preview-label`;

  return (
    <GridComputedColumnsPanelEditorRoot
      ownerState={rootProps}
      className={classes.root}
      onKeyDown={handleRootKeyDown}
      onKeyDownCapture={handleRootKeyDownCapture}
    >
      <GridComputedColumnsPanelEditorBody ownerState={rootProps}>
        <GridComputedColumnsPanelFieldRoot ownerState={rootProps} className={classes.field}>
          <rootProps.slots.baseTextField
            id={nameId}
            inputRef={nameInputRef}
            label={getLocaleText('computedColumnNameLabel')}
            value={draft.headerName}
            onChange={handleNameChange}
            size="small"
            fullWidth
            slotProps={{ htmlInput: { onKeyDown: handleInputKeyDown } }}
            {...rootProps.slotProps?.baseTextField}
          />
        </GridComputedColumnsPanelFieldRoot>
        <GridComputedColumnsPanelFieldRoot ownerState={rootProps} className={classes.field}>
          <rootProps.slots.baseTextField
            id={fieldId}
            label={getLocaleText('computedColumnFieldLabel')}
            value={draft.field}
            onChange={handleFieldChange}
            disabled={isEditing}
            size="small"
            fullWidth
            slotProps={{
              htmlInput: { onKeyDown: handleInputKeyDown, readOnly: isEditing },
            }}
            {...rootProps.slotProps?.baseTextField}
          />
        </GridComputedColumnsPanelFieldRoot>
        <GridComputedColumnsPanelFieldRoot ownerState={rootProps} className={classes.field}>
          <GridComputedColumnsPanelLabel ownerState={rootProps} id={formulaLabelId}>
            {getLocaleText('computedColumnFormulaLabel')}
          </GridComputedColumnsPanelLabel>
          <GridComputedColumnsPanelFormula
            ownerState={rootProps}
            className={classes.formula}
            onMouseDown={handleFormulaSurfaceMouseDown}
          >
            <GridFormulaEditable
              ref={editableRef}
              value={draft.formula}
              ownerCell={previewRowId === null ? null : { id: previewRowId, field: ownerField }}
              a1Notation={a1Notation}
              suggestionsEnabled={!rootProps.disableFormulaAutocomplete}
              popupId={`${id}-formula-popup`}
              ariaLabel={getLocaleText('computedColumnFormulaLabel')}
              errorSpans={errorSpans}
              onValueChange={handleFormulaChange}
              onCommitKey={handleApply}
            />
          </GridComputedColumnsPanelFormula>
          <GridComputedColumnsPanelReferencePane
            excludeField={draftDefinition.field}
            a1Notation={a1Notation}
            onInsert={handleInsert}
          />
        </GridComputedColumnsPanelFieldRoot>
        <GridComputedColumnsPanelFieldRoot ownerState={rootProps} className={classes.field}>
          <GridComputedColumnsPanelFieldRow ownerState={rootProps}>
            <rootProps.slots.baseSelect
              id={typeId}
              labelId={typeLabelId}
              label={getLocaleText('computedColumnTypeLabel')}
              value={draft.type}
              onChange={handleTypeChange}
              size="small"
              fullWidth
              {...rootProps.slotProps?.baseSelect}
            >
              {COLUMN_TYPES.map((type) => (
                <rootProps.slots.baseSelectOption key={type} value={type} native={false}>
                  {getLocaleText(COLUMN_TYPE_LABELS[type])}
                </rootProps.slots.baseSelectOption>
              ))}
            </rootProps.slots.baseSelect>
            {draft.type === 'number' && (
              <rootProps.slots.baseSelect
                id={styleId}
                labelId={styleLabelId}
                label={getLocaleText('computedColumnFormatLabel')}
                value={draft.formatStyle}
                onChange={(event: React.ChangeEvent<HTMLSelectElement>) =>
                  updateDraft({ formatStyle: event.target.value as NumberFormatStyle })
                }
                size="small"
                fullWidth
                {...rootProps.slotProps?.baseSelect}
              >
                {FORMAT_STYLES.map((style) => (
                  <rootProps.slots.baseSelectOption key={style} value={style} native={false}>
                    {getLocaleText(FORMAT_STYLE_LABELS[style])}
                  </rootProps.slots.baseSelectOption>
                ))}
              </rootProps.slots.baseSelect>
            )}
          </GridComputedColumnsPanelFieldRow>
          {draft.type === 'number' && (
            <GridComputedColumnsPanelFieldRow ownerState={rootProps}>
              {draft.formatStyle === 'currency' && (
                <rootProps.slots.baseTextField
                  id={`${id}-currency`}
                  label={getLocaleText('computedColumnFormatCurrencyLabel')}
                  value={draft.currency}
                  onChange={(event: React.ChangeEvent<HTMLInputElement>) =>
                    updateDraft({ currency: event.target.value })
                  }
                  error={currencyInvalid}
                  size="small"
                  fullWidth
                  slotProps={{ htmlInput: { maxLength: 3, onKeyDown: handleInputKeyDown } }}
                  {...rootProps.slotProps?.baseTextField}
                />
              )}
              <rootProps.slots.baseTextField
                id={`${id}-decimals`}
                label={getLocaleText('computedColumnFormatDecimalsLabel')}
                type="number"
                value={draft.decimals}
                onChange={(event: React.ChangeEvent<HTMLInputElement>) =>
                  updateDraft({ decimals: event.target.value })
                }
                error={decimalsInvalid}
                size="small"
                fullWidth
                slotProps={{
                  htmlInput: { min: 0, max: MAX_FRACTION_DIGITS, onKeyDown: handleInputKeyDown },
                }}
                {...rootProps.slotProps?.baseTextField}
              />
            </GridComputedColumnsPanelFieldRow>
          )}
          {draft.type === 'number' && (
            <rootProps.slots.baseSwitch
              checked={draft.grouping}
              onChange={(event: React.ChangeEvent<HTMLInputElement>) =>
                updateDraft({ grouping: event.target.checked })
              }
              size="small"
              label={getLocaleText('computedColumnFormatGroupingLabel')}
              {...rootProps.slotProps?.baseSwitch}
            />
          )}
        </GridComputedColumnsPanelFieldRoot>
        <GridComputedColumnsPanelFieldRoot ownerState={rootProps} className={classes.field}>
          <GridComputedColumnsPanelLabel ownerState={rootProps} id={previewLabelId}>
            {getLocaleText('computedColumnPreviewLabel')}
          </GridComputedColumnsPanelLabel>
          <GridComputedColumnsPanelPreview
            ownerState={rootProps}
            className={classes.preview}
            role="status"
            aria-labelledby={previewLabelId}
          >
            <GridComputedColumnsPanelPreviewRow ownerState={rootProps}>
              {previewRowIndex === null
                ? getLocaleText('computedColumnPreviewNoRows')
                : getLocaleText('computedColumnPreviewRow')(previewRowIndex)}
            </GridComputedColumnsPanelPreviewRow>
            <GridComputedColumnsPanelPreviewValue
              ownerState={rootProps}
              data-error={preview?.error ? 'true' : undefined}
            >
              {preview?.text ?? ''}
            </GridComputedColumnsPanelPreviewValue>
          </GridComputedColumnsPanelPreview>
        </GridComputedColumnsPanelFieldRoot>
        {showValidation && (
          <GridComputedColumnsPanelValidation
            ownerState={rootProps}
            className={classes.validation}
            role="alert"
          >
            {validation.issues.map((issue, index) => (
              <li key={`${issue.code}-${index}`}>{issue.message}</li>
            ))}
          </GridComputedColumnsPanelValidation>
        )}
      </GridComputedColumnsPanelEditorBody>
      <GridComputedColumnsPanelFooter ownerState={rootProps} className={classes.footer}>
        <rootProps.slots.baseButton
          size="small"
          onClick={handleCancel}
          {...rootProps.slotProps?.baseButton}
        >
          {getLocaleText('computedColumnCancelButton')}
        </rootProps.slots.baseButton>
        {isEditing && (
          <rootProps.slots.baseButton
            size="small"
            onClick={handleDelete}
            {...rootProps.slotProps?.baseButton}
          >
            {getLocaleText('computedColumnDeleteButton')}
          </rootProps.slots.baseButton>
        )}
        <rootProps.slots.baseButton
          size="small"
          onClick={handleApply}
          disabled={!canApply}
          {...rootProps.slotProps?.baseButton}
        >
          {getLocaleText(isEditing ? 'computedColumnApplyButton' : 'computedColumnAddButton')}
        </rootProps.slots.baseButton>
      </GridComputedColumnsPanelFooter>
    </GridComputedColumnsPanelEditorRoot>
  );
}

export { GridComputedColumnsPanelEditor };
